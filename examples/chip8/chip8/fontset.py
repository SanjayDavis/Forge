"""Built-in hexadecimal font (0-F), 4x5 sprites.

The FX29 opcode points I at the glyph for a nibble. Each glyph is 5 bytes, one
row per byte (low 4 bits significant). Loaded at 0x50 by the CPU's reset.
"""

GLYPHS = [
    0xF0, 0x90, 0x90, 0x90, 0xF0,  # 0
    0x20, 0x60, 0x20, 0x20, 0x70,  # 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0,  # 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0,  # 3
    0x90, 0x90, 0xF0, 0x10, 0x10,  # 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0,  # 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0,  # 6
    0xF0, 0x10, 0x20, 0x40, 0x40,  # 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0,  # 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0,  # 9
    0xF0, 0x90, 0xF0, 0x90, 0x90,  # A
    0xE0, 0x90, 0xE0, 0x90, 0xE0,  # B
    0xF0, 0x80, 0x80, 0x80, 0xF0,  # C
    0xE0, 0x90, 0x90, 0x90, 0xE0,  # D
    0xF0, 0x80, 0xF0, 0x80, 0xF0,  # E
    0xF0, 0x80, 0xF0, 0x80, 0x80,  # F
]

FONT_BASE = 0x50


def load(mem):
    """Write the 16 glyphs into memory at 0x50. Returns the base address."""
    base = FONT_BASE
    for i, byte in enumerate(GLYPHS):
        mem.write(base + i, byte)
    return base


def glyph(nibble: int) -> bytes:
    """Return the 5-byte sprite for the given nibble (0-15)."""
    nibble &= 0xF
    start = nibble * 5
    return bytes(GLYPHS[start:start + 5])
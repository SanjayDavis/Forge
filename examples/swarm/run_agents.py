HERE = os.path.dirname(os.path.abspath(__file__))
AGENTS = ("agent-a", "agent-b", "agent-c", "agent-d")
MAX_RETRIES = 3
BACKOFF_S = 0.05
POLL_S = 0.2
IDLE_TIMEOUT_S = 60.0
STATUS_DONE = "done"

# ---------------------------------------------------------------------------
# Implementation seam
# ---------------------------------------------------------------------------
class Implementable:
    """Implement a task so its acceptance criteria hold (write real code +
    tests). Raise on failure; the harness will verify_fail + retry."""

    def run(self, task_id, task):
        raise NotImplementedError

class DefaultImplementer(Implementable):
    """Scaffold stub: no-op. Replaced by the real executor in the full run."""

    def run(self, task_id, task):
        return


def _strip_leaked_env():
    """Workers must not inherit the host's PYTHONPATH etc. (hermes-agent
    site-packages would shadow the venv). Returns a clean env dict."""
    env = dict(os.environ)
    for key in ("PYTHONPATH", "UV_PUBLISH_TOKEN", "SWARM_SMOKE_TREE"):
        env.pop(key, None)
    return env


class _WorktreeLock:
    """Cross-process advisory lock on the shared worktree, so pytest probes
    and fault v1<->v2 flips never interleave. Backed by msvcrt (Windows) or
    fcntl (POSIX); falls back to an O_EXCL lockfile. Released automatically
    if the holding process dies."""

    def __init__(self, tree):
        self.path = os.path.join(tree, ".worktree.lock")
        self.fh = None

    def __enter__(self):
        self.fh = open(self.path, "a+b")
        try:
            import msvcrt
            while True:
                try:
                    self.fh.seek(0)
                    msvcrt.locking(self.fh.fileno(), msvcrt.LK_NBLCK, 1)
                    break
                except OSError:
                    time.sleep(0.25)
        except ImportError:
            import fcntl
            fcntl.flock(self.fh.fileno(), fcntl.LOCK_EX)
        return self

    def __exit__(self, *exc):
        try:
            import msvcrt
            self.fh.seek(0)
            msvcrt.locking(self.fh.fileno(), msvcrt.LK_UNLCK, 1)
        except ImportError:
            import fcntl
            fcntl.flock(self.fh.fileno(), fcntl.LOCK_UN)
        self.fh.close()
        return False


class ManifestImplementer(Implementable):
    """The REAL Proof #5 implementer.

    Consumes swarm_manifest.json (generated by source_gen.py) + the
    materialised canonical tree. For every claimed task it writes the task's
    files from the canonical tree, then runs the task's real verify probe
    (pytest suite / py_compile / existence). The three fault tasks repeat the
    cycle with their injected v1 content: probe FAILS -> verification_failed
    is recorded (real reason) -> canonical v2 restored -> probe PASSES ->
    verification_passed. No task_retried op is ever emitted; the red-green
    cycle happens inside one claim, per PHASE2_DESIGN.md §2/§4.
    """

    # probe name -> what to run when the manifest says so
    def __init__(self, k, can_dir, worktree, manifest_path):
        self.k = k
        self.can = can_dir          # canonical SOURCES materialisation (read-only)
        self.tree = worktree        # running worktree (grown claim by claim)
        os.makedirs(self.tree, exist_ok=True)
        with open(manifest_path, encoding="utf-8") as fh:
            self.m = json.load(fh)
        self.faults = self.m.get("fault_plans", {})

    # -- probes -----------------------------------------------------------
    def _run_pytest(self, target):
        env = _strip_leaked_env()
        r = subprocess.run(
            [sys.executable, "-m", "pytest", target, "-q",
             "-p", "no:cacheprovider", "--disable-warnings"],
            cwd=self.tree, env=env, capture_output=True, text=True, timeout=600)
        return r.returncode == 0, _tail(r.stdout, r.stderr)

    def _prefetch_package(self, exclude=()):
        """pytest probes import the whole ``swarm`` package + pytest fixture
        glue. The proposal DAG only orders *tasks*, not import closures, so
        copy the package skeleton from canonical before any probe runs. The
        owning tasks still write these files themselves at claim time —
        idempotent, byte-identical — so no claim is bypassed. ``exclude``
        keeps an in-flight fault file (v1) from being clobbered."""
        exclude = set(exclude)
        for rel in self.m.get("probe_bootstrap", []):
            if rel in exclude:
                continue
            src = os.path.join(self.can, rel)
            dst = os.path.join(self.tree, rel)
            if not os.path.exists(src):
                continue
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(src, "rb") as fin, open(dst, "wb") as fout:
                fout.write(fin.read())

    def _probe(self, plan, fault=None):
        kind, *targets = plan["verify"]
        if kind == "pytest":
            self._prefetch_package(exclude=[fault["file"]] if fault else ())
            for t in targets:
                ok, msg = self._run_pytest(t)
                if not ok:
                    return False, f"{t}: {msg}"
            return True, ""
        if kind == "compile":
            env = _strip_leaked_env()
            for t in targets:
                if t.endswith(".py"):
                    r = subprocess.run(
                        [sys.executable, "-m", "py_compile", t],
                        cwd=self.tree, env=env, capture_output=True, text=True,
                        timeout=120)
                    if r.returncode != 0:
                        return False, f"compile {t}: {_tail(r.stdout, r.stderr)}"
                elif t.endswith(".sh"):
                    r = subprocess.run(
                        ["bash", "-n", t], cwd=self.tree, env=env,
                        capture_output=True, text=True, timeout=120)
                    if r.returncode != 0:
                        return False, f"bash -n {t}: {_tail(r.stdout, r.stderr)}"
            return True, ""
        if kind == "exists":
            missing = [t for t in targets
                       if not os.path.exists(os.path.join(self.tree, t))]
            return (not missing), f"missing: {missing}"
        return False, f"unknown probe {kind!r}"

    # -- per-task implementation ------------------------------------------
    def run(self, task_id, task):
        """Implement the claimed task. The whole write+probe section is
        serialised across agents by the worktree lock — probes and the fault
        v1<->v2 flips share the same file layout, so interleaving would make
        results non-deterministic."""
        with _WorktreeLock(self.tree):
            plan = self.m["tasks"][task_id]
            fault = self.faults.get(task_id)
            if fault is None:
                self._plain(task_id, plan)
                return
            self._faulty(task_id, plan, fault)

    def _write_files(self, plan):
        """Write this task's files into the worktree, copied from the
        canonical materialisation — REAL authorship at claim time. A task's
        verify probe only passes when the files it imports were written by
        its (already-done) dependencies."""
        for rel in plan.get("files", []):
            if not rel:
                continue
            src = os.path.join(self.can, rel)
            dst = os.path.join(self.tree, rel)
            if not os.path.exists(src):
                raise RuntimeError(f"canonical file missing: {rel}")
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(src, "rb") as fin, open(dst, "wb") as fout:
                fout.write(fin.read())

    def _plain(self, task_id, plan):
        self._write_files(plan)   # canonical files exist by construction
        ok, msg = self._probe(plan)
        if not ok:
            raise RuntimeError(f"verification failed: {msg}")

    def _write_needs(self, fault):
        """Write the review tests the fault's verify probe references (they
        are structured part of the fault plan, not of any proposal task)."""
        for rel in fault.get("needs", []):
            if not rel:
                continue
            src = os.path.join(self.can, rel)
            dst = os.path.join(self.tree, rel)
            if not os.path.exists(src):
                raise RuntimeError(f"fault review file missing: {rel}")
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(src, "rb") as fin, open(dst, "wb") as fout:
                fout.write(fin.read())

    def _faulty(self, task_id, plan, fault):
        """Red-green cycle inside ONE claim (no retry op):
            v1 (defective)  -> probe FAILS  -> k.verify_fail(reason)
            v2 (canonical)  -> probe PASSES
        The task's canonical file + the review tests are written into the
        worktree first (authorship), then the v1 defect is applied on top."""
        # authorship: the task's own file(s) and the review probes it needs
        self._write_files(plan)
        self._write_needs(fault)
        # stage 1: swap in the defective v1 content
        fpath = os.path.join(self.tree, fault["file"])
        if not os.path.exists(fpath):
            raise RuntimeError(f"fault target missing: {fault['file']}")
        orig = open(fpath, encoding="utf-8").read()
        with open(fpath, "w", encoding="utf-8", newline="") as fh:
            fh.write(fault["v1"])
        # probe MUST fail on v1 — otherwise the injected fault is inert
        ok, msg = self._probe(plan, fault=fault)
        reason = f"[{fault['title']}] probe expected FAIL on v1"
        if ok:
            with open(fpath, "w", encoding="utf-8", newline="") as fh:
                fh.write(orig)
            raise RuntimeError(reason + " — v1 unexpectedly PASSED")
        # record the genuine failure on the task (in_progress -> needs_revision)
        reason_one = f"{reason}: {msg}".replace("\r", " ").replace("\n", " ")
        self.k.verify_fail(task_id, reason_one[:2000])
        # stage 2: restore the canonical (green) implementation
        with open(fpath, "w", encoding="utf-8", newline="") as fh:
            fh.write(orig)
        ok, msg = self._probe(plan, fault=fault)
        if not ok:
            raise RuntimeError(f"canonical restore still fails: {msg}")
        # green — harness's verify_pass carries the task to done.

def implementer_factory(k=None, workdir=None, manifest=None, tree=None, work=None):
    """Build the per-worker implementation seam. Real run: SWARM_MANIFEST is
    set -> ManifestImplementer (real files + real pytest probes), writing
    into the worktree under the workdir. Harness self-test:
    SWARM_SMOKE_TREE set -> file-writing smoke implementer."""
    manifest = manifest or os.environ.get("SWARM_MANIFEST")
    tree = tree or os.environ.get("SWARM_TREE")
    if manifest:
        my = work or os.environ.get("SWARM_WORKTREE")
        if not my:
            base = os.path.dirname(manifest)
            my = os.path.join(base, "worktree")
        return ManifestImplementer(k, tree, my, manifest)
    smoke = os.environ.get("SWARM_SMOKE_TREE")
    if smoke:
        return _SmokeImplementer(smoke)
    return DefaultImplementer()


def subsystems():
    """Ownership sidecar. Path overridable via SWARM_SUBSYSTEMS so the smoke
    self-test can point spawned workers at a tiny sidecar."""
    path = os.environ.get("SWARM_SUBSYSTEMS", os.path.join(HERE, "subsystems.json"))
    with open(path, encoding="utf-8") as f:
        return json.load(f)

def owned_task_ids(agent):
    return set(subsystems()["agents"][agent]["tasks"])

def init_project(workdir, proposal_path=None):
    os.makedirs(workdir, exist_ok=True)
    k = Kernel(workdir)
    if proposal_path and not k.export_events():
        with open(proposal_path, encoding="utf-8") as f:
            k.import_events(json.load(f)["events"])
    return k

def _claim(k, task_id):
    """Claim a ready task. Returns True on success; backoff+retry on races
    (another agent's process may have claimed the same snapshot)."""
    for attempt in range(1 + MAX_RETRIES):
        try:
            k.start(task_id)
            return True
        except Exception:
            if attempt == MAX_RETRIES:
                return False
            time.sleep(BACKOFF_S * (attempt + 1))
    return False

def implement_with_retry(k, task_id, impl):
    """Run the implementation seam. Genuine failures are recorded ONCE via
    k.verify_fail (real reason) and the claim is abandoned; the task stays
    needs_revision for a human (or a later claim) to fix. The three planned
    fault tasks never surface here — their red-green cycle is handled
    INSIDE ManifestImplementer, so no task_retried op is ever produced.
    Returns (ok, reason)."""
    try:
        impl.run(task_id, k.inspect(task_id))
        return True, ""
    except Exception as e:  # unexpected/genuine failure — record it as-is
        reason = f"{type(e).__name__}: {e}".replace("\r", " ").replace("\n", " ")
        try:
            k.verify_fail(task_id, reason[:2000])
        except Exception:
            pass
        return False, reason

